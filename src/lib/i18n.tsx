const RTL: Lang[] = [];

/** Bumped so previous default-to-SL sessions don't keep forcing Slovenian. */
const STORAGE_KEY = "skybooplan.lang.v2";

function isUsableTranslation(value: string | undefined): value is string {
  return typeof value === "string" && value.trim().length > 0;
}

/**
 * Fallback chain for lookup. Non-SL locales never fall back to Slovenian.
 * Partial locale packs (es/fr/it/de) are merged with EN at build time via withEnglishFallback.
 */
export function translationFallbackChain(lang: Lang): Lang[] {
  if (lang === "sl") return ["sl", "en"];
  if (lang === "en") return ["en"];
  return [lang, "en"];
}

/** Normalize persisted / picked codes so incomplete packs do not stick as UI language. */
export function normalizeAppLang(code: string): Lang {
  const raw = (code ?? "").trim().toLowerCase().slice(0, 2);
  if (RETIRED_UI_LANGS.has(raw)) return "en";
  if ((SUPPORTED_LANGS as readonly string[]).includes(raw)) return raw as Lang;
  return "en";
}

export function readStoredLang(): Lang {
  if (typeof window === "undefined") return "en";
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored) return normalizeAppLang(stored);
  } catch {}
  return "en";
}

type I18nCtx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  currency: PlanCurrency;
  setCurrency: (c: PlanCurrency) => void;
  formatMoney: (amount: number) => string;
  currencySymbol: string;
  t: (key: keyof typeof en) => string;
  dir: "ltr" | "rtl";
};

const Ctx = createContext<I18nCtx | null>(null);

function lookupTranslation(lang: Lang, key: keyof typeof en): string {
  for (const code of translationFallbackChain(lang)) {
    const v = dicts[code]?.[key];
    if (isUsableTranslation(v)) return v;
  }
  const master = en[key];
  if (isUsableTranslation(master)) return master;
  if (import.meta.env.DEV) {
    console.warn(`[i18n] Missing translation for "${String(key)}" (lang=${lang})`);
  }
  return String(key);
}

export function translate(lang: Lang, key: keyof typeof en): string {
  return lookupTranslation(lang, key);
}

/** Look up a key in active or dormant dicts (for stripping old es/fr/it teasers). */
export function translateDictLang(lang: string, key: keyof typeof en): string {
  const raw = (lang ?? "").trim().toLowerCase().slice(0, 2);
  if (raw in dicts) {
    const v = dicts[raw as DictLang]?.[key];
    if (isUsableTranslation(v)) return v;
  }
  return lookupTranslation(normalizeAppLang(raw), key);
}

function isNetworkFetchError(message: string): boolean {
  const m = message.trim().toLowerCase();
  return (
    m === "load failed" ||
    m === "failed to fetch" ||
    m.includes("networkerror") ||
    m.includes("network request failed") ||
    m.includes("fetch failed")
  );
}

/** Strip internal provider / infra jargon before showing errors to travelers. */
function sanitizeUserFacingError(message: string): string {
  const m = message.trim();
  if (!m) return m;
  const lower = m.toLowerCase();
  if (
    lower.includes("duffel") ||
    lower.includes("make history") ||
    lower.includes("make.com") ||
    lower.includes("make →") ||
    lower.includes("http/duffel") ||
    lower.includes("webhook") ||
    lower.includes("data store")
  ) {
    if (lower.includes("brez letov") || lower.includes("no flights") || lower.includes("empty")) {
      return "heroSearch.empty";
    }
    if (lower.includes("timeout") || lower.includes("predolgo") || lower.includes("too long")) {
      return lower.includes("načrt") || lower.includes("plan") || lower.includes("generir")
        ? "error.planTimeout"
        : "heroSearch.timeout";
    }
    return "heroSearch.error";
  }
  if (
    m === "Generiranje načrta je predolgo trajalo brez odgovora. Poskusi znova." ||
    /generiranje.*predolgo/i.test(m) ||
    /took too long without a response/i.test(m)
  ) {
    return "error.planTimeout";
  }
  const partial = m.match(/ustavilo po (\d+)\. dnevu/i) || m.match(/after day (\d+)/i);
  if (partial) {
    return `error.planTimeoutPartial:${partial[1]}`;
  }
  return m;
}

export function resolveErrorMessage(
  t: (key: keyof typeof en) => string,
  code: string,
): string {
  const cleaned = sanitizeUserFacingError(code);
  if (cleaned.startsWith("error.duffelApi:")) {
    const status = cleaned.slice("error.duffelApi:".length);
    return t("error.duffelApi").replace("{status}", status);
  }
  if (cleaned.startsWith("error.planTimeoutPartial:")) {
    const day = cleaned.slice("error.planTimeoutPartial:".length);
    return t("error.planTimeoutPartial" as keyof typeof en).replace("{day}", day);
  }
  if (isNetworkFetchError(cleaned)) return t("error.networkFetch");
  if (cleaned in dicts.en) return t(cleaned as keyof typeof en);
  // Never show raw infra strings — fall back to a generic search/plan error.
  if (/duffel|make\.com|webhook|gemini pro/i.test(cleaned)) {
    return t("heroSearch.error");
  }
  return cleaned;
}

/** Soft informational quota messages — not red “system failure” banners. */
export function isSoftQuotaError(code: string | null | undefined): boolean {
  return Boolean(code?.startsWith("error.quota"));
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readStoredLang);
  const [currency, setCurrencyState] = useState<PlanCurrency>(readStoredCurrency);

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = lang;
      document.documentElement.dir = RTL.includes(lang) ? "rtl" : "ltr";
    }
  }, [lang]);

  const value = useMemo<I18nCtx>(() => {
    return {
      lang,
      setLang: (l) => {
        const normalized = normalizeAppLang(l);
        setLangState(normalized);
        try { localStorage.setItem(STORAGE_KEY, normalized); } catch {}
      },
      currency,
      setCurrency: (c) => {
        const normalized = normalizePlanCurrency(c);
        setCurrencyState(normalized);
        persistCurrency(normalized);
      },
      formatMoney: (amount) => formatPlanMoney(amount, currency),
      currencySymbol: currencySymbol(currency),
      t: (key) => lookupTranslation(lang, key),
      dir: RTL.includes(lang) ? "rtl" : "ltr",
    };
  }, [lang, currency]);

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
  const c = useContext(Ctx);
  if (!c) {
    // Safe fallback if provider missing (e.g. during SSR shell)
    const fallbackCurrency = readStoredCurrency();
    return {
      lang: readStoredLang(),
      setLang: () => {},
      currency: fallbackCurrency,
      setCurrency: () => {},
      formatMoney: (amount) => formatPlanMoney(amount, fallbackCurrency),
      currencySymbol: currencySymbol(fallbackCurrency),
      t: (key) => lookupTranslation(readStoredLang(), key),
      dir: "ltr",
    };
  }
  return c;
}

export function useT() {
  return useI18n().t;
}
